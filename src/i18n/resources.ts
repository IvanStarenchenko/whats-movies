export const getNormalizedLanguage = (
	language?: string | null
): AppLanguage => {
	const normalized = language?.split('-')[0]
	return normalized === 'en' ? 'en' : 'ru'
}

export const getTmdbLanguage = (language?: string | null): TmdbLanguage =>
	getNormalizedLanguage(language) === 'en' ? 'en-US' : 'ru-RU'

export const getIntlLocale = (language?: string | null) =>
	getNormalizedLanguage(language) === 'en' ? 'en-US' : 'ru-RU'

export const getWatchRegion = (language?: string | null) =>
	getNormalizedLanguage(language) === 'en' ? 'US' : 'RU'

